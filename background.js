// =============================================================================
// Фоновый скрипт расширения (service worker).
//
// Работает "в фоне" и не имеет своей страницы: его задача — реагировать
// на события браузера. Здесь мы создаём контекстное меню у иконки
// расширения и обрабатываем выбор его пунктов.
// =============================================================================

// -----------------------------------------------------------------------------
// Создание пунктов меню.
// onInstalled срабатывает один раз при установке расширения и при каждом
// обновлении. Создавать меню нужно именно здесь, иначе после перезапуска
// браузер сам восстановит пункты, и мы получим дубликаты.
// -----------------------------------------------------------------------------
chrome.runtime.onInstalled.addListener(() => {
    chrome.contextMenus.create({
        id: "openSettings",
        title: "Настройки",
        // "action" означает: пункт виден при клике правой кнопкой
        // по иконке расширения на панели браузера
        contexts: ["action"]
    });
});

// -----------------------------------------------------------------------------
// Обработка выбора пунктов меню.
// info — по какому пункту кликнули (info.menuItemId)
// -----------------------------------------------------------------------------
chrome.contextMenus.onClicked.addListener((info) => {
    if (info.menuItemId === "openSettings") {
        openSettings();
    }
});

/**
 * Открывает страницу новой вкладки, где окно настроек раскрывается
 * сразу. Параметр ?settings=1 подхватывает newtab/app.js.
 */
function openSettings() {
    chrome.tabs.create({ url: chrome.runtime.getURL("newtab/index.html?settings=1") });
}
